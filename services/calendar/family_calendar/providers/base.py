from typing import Protocol, runtime_checkable


@runtime_checkable
class CalendarProvider(Protocol):
    """Account-bound pilot adapter; raw hrefs and ICS stay inside the owner process."""

    connection_id: str

    async def discover(self) -> list[dict]: ...
    async def read(self, href: str) -> dict | None: ...
    async def read_window(self, collection: str, start: str, end: str) -> dict: ...
    async def put(self, href: str, data: bytes, *, etag: str | None = None, create: bool = False): ...
    async def delete(self, href: str, etag: str): ...
